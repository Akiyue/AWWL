"""Generate the spectral band tables from the sample images on disk.

Separate from ``make_tables.py`` because the band deviations are not recorded
in the training ledgers; they are recomputed from the sampled PNGs.

The statistic is the one the pricing measurements use
(:mod:`awwl.evaluation.price_fid`): per image, the luminance log-magnitude
spectrum in dB, averaged within integer-radius bins about the ``fftshift``
centre and then over images, compared with the same profile of the reference
set. Every sample of a run (10,000) and every reference image (the 50,000
CIFAR-10 training images) is used, in sorted file order. Bins are split by
index into three equal thirds; the radii of each band are printed in the
captions, computed from the profile length rather than typed.

Profiles are cached as ``.npy`` files under ``runs/pricing/cache``, with the
same names the pricing job (``scripts/price_fid.py``) uses, so whichever
process computes a profile first saves the other the work. Writes go to a
temporary name followed by ``os.replace``, so a reader never sees a partial
file.

Tables written (``paper/tables``):

``bands.tex``          signed deviation per band at epoch 199 (DDIM-100)
``bands_ddpm1000.tex`` the same for the ancestral-sampler samples
``deficit_budget.tex`` the high-band deficit against training budget

Usage::

    python scripts/make_band_table.py              # all three tables
    python scripts/make_band_table.py --only bands --workers 8
    python scripts/make_band_table.py --no-compute # cached profiles only
"""

