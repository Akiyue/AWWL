def available_arms(source: SampleSet, arms: Sequence[tuple[str, str]], seeds: Sequence[int]):
    """Arms with at least two seeds of samples (or cached profiles)."""
    out = []
    for arm, label in arms:
        have = sum(1 for s in seeds if source.cache(arm, s).exists() or source.folder(arm, s).is_dir())
        if have >= 2:
            out.append((arm, label))
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=ROOT / "paper" / "tables")
    parser.add_argument("--only", choices=["bands", "ddpm", "trajectory"], action="append")
    parser.add_argument("--workers", type=int, default=6)
    parser.add_argument("--no-compute", action="store_true", help="use cached profiles only")
    args = parser.parse_args()

    compute = not args.no_compute
    reference = reference_profile(compute=compute)
    if reference is None:
        print("no reference profile and no reference images; nothing to do")
        return 1
    which = set(args.only or ["bands", "ddpm", "trajectory"])
    args.out.mkdir(parents=True, exist_ok=True)
    written = []

    if "bands" in which:
        src = ddim()
        arms = available_arms(src, ARMS, SEEDS)
        devs = deviations(src, [a for a, _ in arms], SEEDS, reference, compute=compute, workers=args.workers)
        if "mse" in devs:
            (args.out / "bands.tex").write_text(
                build_band_table(devs, reference, arms=arms), encoding="utf-8"
            )
            written.append("bands.tex")
    if "ddpm" in which:
        src = ddpm()
        arms = available_arms(src, [(a, lab) for a, lab in ARMS if a in DDPM_ARMS], SEEDS)
        devs = deviations(src, [a for a, _ in arms], SEEDS, reference, compute=compute, workers=args.workers)
        if "mse" in devs:
            (args.out / "bands_ddpm1000.tex").write_text(
                build_band_table(
                    devs, reference, arms=arms, label="tab:bands-ddpm", sampler="DDPM-1000"
                ),
                encoding="utf-8",
            )
            written.append("bands_ddpm1000.tex")
    if "trajectory" in which:
        anchor, long = trajectory_data(reference, compute=compute, workers=args.workers)
        (args.out / "deficit_budget.tex").write_text(build_trajectory_table(anchor, long), encoding="utf-8")
        written.append("deficit_budget.tex")

    for name in written:
        print(f"wrote {args.out / name}")
    return 0 if written else 1


if __name__ == "__main__":
    raise SystemExit(main())
