# Rows of Table bands: the arms whose spectra the text discusses (the three
# of the replication, the normalisation controls with AWWL's timestep
# component alone, the equation as printed, and the two comparisons with a
# timestep term or a Fourier basis), in the presentation order of
# make_tables.ROWS and under its display names. An arm appears once at least
# two seeds of samples exist (``MIN_SEEDS`` can demand more: the timestep-only
# arm needs all five). make_numbers.py writes a macro per arm listed here, so
# an arm added here needs a macro code there (make_numbers.CODE).
_BAND_KEYS = (
    "mse", "awwl", "static_wavelet", "awwl_eq7", "awwl_normalized", "awwl_norm_matched",
    "awwl_grad_matched_mean", "awwl_grad_matched", _mt.TIMESTEP_ARM, "min_snr", "focal_frequency",
)
ARMS: list[tuple[str, str]] = [(k, _mt.NAMES[k]) for k in sorted(_BAND_KEYS, key=_mt.ORDER.get)]
MIN_SEEDS: dict[str, int] = {_mt.TIMESTEP_ARM: _mt.TIMESTEP_SEEDS}
DDPM_ARMS = ("mse", "static_wavelet", "awwl")
TRAJECTORY_EPOCHS = (199, 299, 399, 499, 599, 699, 799)
TRAJECTORY_TABLE_EPOCHS = (199, 399, 799)
TRAJECTORY_SEEDS = (1, 2, 3)

PREAMBLE = (
    "% Generated by scripts/make_band_table.py --- do not edit by hand.\n"
    "% Recomputed from the sampled images (all samples, all reference images).\n"
)


# --------------------------------------------------------------------------
# Profiles and their cache


@dataclass(frozen=True)
class SampleSet:
    """Where one family of sample folders lives, and where its profiles cache.

    ``dataset`` names the cache directory and matches the dataset keys of
    ``scripts/price_fid.py`` (``cifar10`` is ``runs/phase0``, ``cifar10_long``
    is ``runs/converged``), so the two scripts share cached profiles.
    """

    dataset: str
    root: Path
    epoch: int
    sub: str = "samples"
    suffix: str = ""

    def folder(self, arm: str, seed: int) -> Path:
        return self.root / f"{arm}_s{seed}" / self.sub / f"ep{self.epoch}"

    def cache(self, arm: str, seed: int) -> Path:
        return CACHE / self.dataset / "profiles" / f"{arm}_s{seed}_ep{self.epoch}{self.suffix}.npy"


def ddim(epoch: int = EPOCH) -> SampleSet:
    return SampleSet("cifar10", ROOT / "runs" / "phase0", epoch)


def ddpm(epoch: int = EPOCH) -> SampleSet:
    return SampleSet("cifar10", ROOT / "runs" / "phase0", epoch, "samples_ddpm1000", "_ddpm1000")


def long_run(epoch: int) -> SampleSet:
    return SampleSet("cifar10_long", ROOT / "runs" / "converged", epoch)


def atomic_save(path: Path, array: np.ndarray) -> None:
    """Save ``array`` to ``path`` through a temporary name and ``os.replace``."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.stem}.{os.getpid()}.tmp.npy")
    np.save(tmp, np.asarray(array, dtype=np.float64))
    os.replace(tmp, path)


def _compute(folder: str, cache: str) -> str:
    """Worker: profile one folder and cache it. Returns the cache path."""
    path = Path(cache)
    if not path.exists():
        atomic_save(path, pf.radial_profile(pf.load_images(folder)))
    return cache


def reference_profile(real: Path = REAL, *, compute: bool = True) -> np.ndarray | None:
    path = CACHE / "cifar10" / "ref_profile.npy"
    if path.exists():
        return np.load(path)
    if not compute or not Path(real).is_dir():
        return None
    profile = pf.radial_profile(pf.load_images(real))
    atomic_save(path, profile)
    return profile


#: Samples per run (``sample.num_samples`` of every CIFAR-10 manifest). The
#: sampling job writes straight into ``samples/ep<N>``, so a folder with fewer
#: images is still being filled; profiling it would cache the profile of a
#: partial set, permanently and under the name the pricing job also reads.
EXPECTED_SAMPLES = 10_000


def is_complete(folder: Path, expected: int | None = None) -> bool:
    """True once ``folder`` holds at least ``expected`` (default :data:`EXPECTED_SAMPLES`) images."""
    need = EXPECTED_SAMPLES if expected is None else expected
    try:
        return len(pf.list_images(folder)) >= need
    except (FileNotFoundError, NotADirectoryError):
        return False


def ensure_profiles(jobs: Iterable[tuple[Path, Path]], *, workers: int = 4, compute: bool = True) -> None:
    """Compute every missing cached profile among ``(folder, cache)`` pairs.

    Folders that are not yet complete (see :data:`EXPECTED_SAMPLES`) are
    skipped, not profiled, so a sampling job in progress cannot poison the
    shared cache.
    """
    if not compute:
        return
    todo = []
    for f, c in jobs:
        if c.exists() or not f.is_dir():
            continue
        if is_complete(f):
            todo.append((f, c))
        else:
            print(f"  skipped {f}: fewer than {EXPECTED_SAMPLES} images (still sampling?)", flush=True)
    if not todo:
        return
    print(f"computing {len(todo)} profile(s) with {workers} worker(s)", flush=True)
    if workers <= 1:
        for f, c in todo:
            _compute(str(f), str(c))
            print(f"  cached {c}", flush=True)
        return
    with ProcessPoolExecutor(max_workers=workers) as pool:
        futures = [pool.submit(_compute, str(f), str(c)) for f, c in todo]
        for fut in as_completed(futures):
            print(f"  cached {fut.result()}", flush=True)


def deviations(
    source: SampleSet,
    arms: Sequence[str],
    seeds: Sequence[int],
    reference: np.ndarray,
    *,
    compute: bool = True,
    workers: int = 4,
) -> dict[str, dict[int, list[float]]]:
    """``{arm: {seed: [low, mid, high]}}`` signed deviations in dB."""
    jobs = [(source.folder(a, s), source.cache(a, s)) for a in arms for s in seeds]
    ensure_profiles(jobs, workers=workers, compute=compute)
    out: dict[str, dict[int, list[float]]] = {}
    for arm in arms:
        for seed in seeds:
            path = source.cache(arm, seed)
            if path.exists():
                out.setdefault(arm, {})[seed] = pf.band_deviations(np.load(path), reference)
    return out


def band_edges(n_bins: int, bands: int = 3) -> list[tuple[int, int]]:
    """Inclusive radius range of each band, exactly as ``band_deviations`` splits it."""
    edges = np.linspace(0, n_bins, bands + 1).astype(int)
    return [(int(a), int(b) - 1) for a, b in zip(edges[:-1], edges[1:], strict=True)]


def edges_text(reference: np.ndarray) -> str:
    (l0, l1), (m0, m1), (h0, h1) = band_edges(len(reference))
    return (
        f"Bands are thirds of the integer radial bins: radii {l0}--{l1} (low), "
        f"{m0}--{m1} (mid) and {h0}--{h1} (high), in cycles per image, where "
        f"the axial Nyquist radius is {_nyquist()}. A band's value is the unweighted "
        f"mean of its bins' deviations, so each radius counts once whatever its number "
        f"of coefficients."
    )


def _nyquist() -> int:
    # CIFAR-10 is 32x32, so the axis Nyquist radius is 16; the high band also
    # holds the diagonal bins beyond it. Read from an image rather than typed.
    try:
        first = pf.list_images(REAL)[0]
        from PIL import Image

        with Image.open(first) as im:
            return min(im.size) // 2
    except Exception:  # pragma: no cover - reference set absent
        return 16


# --------------------------------------------------------------------------
# Statistics (sample SD, t-interval, paired t-test), shared with make_tables


def _stats():
    import make_tables  # noqa: PLC0415 - sibling script

    return make_tables


def _cell_mean_sd(values: Sequence[float], digits: int = 2) -> str:
    mt = _stats()
    return "$" + mt.fnum(st.mean(values), digits) + r" \pm " + mt.fnum(mt.sample_sd(values), digits) + "$"


# --------------------------------------------------------------------------
# Table bands (DDIM-100 and DDPM-1000)


def build_band_table(
    devs: dict[str, dict[int, list[float]]],
    reference: np.ndarray,
    *,
    arms: Sequence[tuple[str, str]],
    baseline: str = "mse",
    label: str = "tab:bands",
    sampler: str = "DDIM-100",
    epoch: int = EPOCH,
) -> str:
    mt = _stats()
    present = [(a, lab) for a, lab in arms if a in devs and len(devs[a]) >= MIN_SEEDS.get(a, 2)]
    uneven = any(len(devs[a]) < len(SEEDS) for a, _lab in present)
    base = devs.get(baseline, {})
    n_ref = _count_images(REAL)
    lines = [
        PREAMBLE,
        r"\begin{table}[tbp]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Signed deviation of the samples' radial luminance spectrum from "
        r"the reference set's, in dB, at epoch " + str(epoch) + r" (" + sampler + r"); "
        r"negative means too little energy. Every sample of each run and all "
        + mt.fint(n_ref) + r" CIFAR-10 training images enter the profiles. "
        + edges_text(reference) + r" Mean $\pm$ sample standard deviation over "
        + (r"seeds (five unless a superscript gives the number)." if uneven else "five seeds.")
        + r" The last two columns pair each seed "
        r"with its own " + baseline.upper() + r" run in the high band: the difference of "
        r"deviations (positive means more high-frequency energy than "
        + baseline.upper() + r"), its 95\% $t$-interval and the two-sided paired "
        r"$t$-test $p$, uncorrected.}",
        r"\label{" + label + "}",
        r"\begin{tabular}{" + (mt.name_column("4.6cm") if any(len(lab) > 30 for _a, lab in present)
                                 else "l") + "rrrrr}",
        r"\toprule",
        r"Configuration & Low & Mid & High & $\Delta$ high [95\% CI] & $p$ \\",
        r"\midrule",
    ]
    for arm, lab in present:
        by_seed = devs[arm]
        n = len(by_seed)
        sup = "" if n >= len(SEEDS) else r"\,\textsuperscript{" + str(n) + "}"
        cells = [
            _cell_mean_sd([v[b] for v in by_seed.values()]) for b in (0, 1, 2)
        ]
        if arm == baseline:
            cells += ["---", "---"]
        else:
            res = mt.paired({s: v[2] for s, v in by_seed.items()}, {s: v[2] for s, v in base.items()})
            if res is None:
                cells += ["---", "---"]
            else:
                cells += [mt.fcell_ci(res, 2), "$" + mt.fp(res.p) + "$"]
        lines.append(lab + sup + " & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def _count_images(folder: Path) -> int:
    try:
        return len(pf.list_images(folder))
    except FileNotFoundError:
        return 0


