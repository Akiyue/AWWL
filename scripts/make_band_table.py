# Table deficit-budget


def trajectory_data(reference: np.ndarray, *, compute: bool = True, workers: int = 4):
    """High-band deviations for the budget analysis.

    Returns ``(anchor, long)``: ``anchor`` is the 200-epoch EMA recipe at its
    annealed end (``runs/phase0`` ``mse_ema``/``awwl_ema``, epoch 199), and
    ``long`` maps each checkpoint of the 800-epoch EMA runs to the same
    structure. Both are ``{arm: {seed: high-band deviation}}``.
    """
    anchor_raw = deviations(
        ddim(EPOCH), ("mse_ema", "awwl_ema"), TRAJECTORY_SEEDS, reference,
        compute=compute, workers=workers,
    )
    anchor = {
        "mse": {s: v[2] for s, v in anchor_raw.get("mse_ema", {}).items()},
        "awwl": {s: v[2] for s, v in anchor_raw.get("awwl_ema", {}).items()},
    }
    long: dict[int, dict[str, dict[int, float]]] = {}
    for epoch in TRAJECTORY_EPOCHS:
        raw = deviations(
            long_run(epoch), ("mse", "awwl"), TRAJECTORY_SEEDS, reference,
            compute=compute, workers=workers,
        )
        long[epoch] = {a: {s: v[2] for s, v in raw.get(a, {}).items()} for a in ("mse", "awwl")}
    return anchor, long


def _fid_by_seed(ledger: Path, group: str, epoch: int) -> dict[int, float]:
    mt = _stats()
    rows = mt.load_eval(ledger, epoch=epoch)
    return mt.by_seed(rows, group, "fid")


def build_trajectory_table(anchor, long, *, epochs: Sequence[int] = TRAJECTORY_TABLE_EPOCHS) -> str:
    """The high-band deficit against training budget.

    The deficit is reported as a positive magnitude, D = -(signed high-band
    deviation). Two comparisons are given for MSE because they answer
    different questions: against the same run's epoch-199 checkpoint (within
    one schedule, where checkpoints differ in learning-rate phase as well as
    in budget) and against the annealed end of the 200-epoch EMA recipe (end
    against end).
    """
    mt = _stats()
    phase0 = ROOT / "runs" / "phase0" / "results.jsonl"
    converged = ROOT / "runs" / "converged" / "results.jsonl"

    def neg(d: dict[int, float]) -> dict[int, float]:
        return {s: -v for s, v in d.items()}

    first = epochs[0]
    rows_out = []
    specs = [("200 ep., end (199)", anchor, _fid_by_seed(phase0, "mse_ema", EPOCH), None)]
    for e in epochs:
        label = f"800 ep., end ({e})" if e == max(TRAJECTORY_EPOCHS) else f"800 ep., epoch {e}"
        specs.append((label, long.get(e, {}), _fid_by_seed(converged, "mse", e), e))
    for label, data, fid, epoch in specs:
        mse = neg(data.get("mse", {}))
        awwl = neg(data.get("awwl", {}))
        if len(mse) < 2 or len(awwl) < 2:
            continue
        cells = []
        cells.append(_cell_mean_sd(list(fid.values())) if len(fid) >= 2 else "---")
        cells.append(_cell_mean_sd(list(mse.values())))
        cells.append(_cell_mean_sd(list(awwl.values())))
        corr = mt.paired(mse, awwl)  # D_mse - D_awwl: what AWWL corrects
        cells.append(mt.fcell_ci(corr, 2) if corr else "---")
        if epoch is None or epoch == first:
            cells.append("---")
        else:
            within = mt.paired(mse, neg(long.get(first, {}).get("mse", {})))
            cells.append(mt.fcell_ci(within, 2) if within else "---")
        if epoch is None:
            cells.append("---")
        else:
            end = mt.paired(mse, neg(anchor.get("mse", {})))
            cells.append(mt.fcell_ci(end, 2) if end else "---")
        rows_out.append(label + " & " + " & ".join(cells) + r" \\")

    n = len(TRAJECTORY_SEEDS)
    lines = [
        PREAMBLE,
        r"\begin{table}[tbp]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{2.5pt}",
        r"\caption{High-band spectral deficit (dB; minus the signed high-band deviation "
        r"of Table~\ref{tab:bands}, so larger means less high-frequency energy) and FID "
        r"against training budget, all with EMA, "
        + mt.cw(n) + r" seeds, DDIM-100 samples. The first row is the annealed end of "
        r"the 200-epoch schedule; the others are checkpoints of the 800-epoch "
        r"schedule, whose early checkpoints are taken at a high learning rate. Mean "
        r"$\pm$ sample standard deviation over seeds. AWWL's correction is MSE's deficit "
        r"minus AWWL's, paired by seed. The last two columns "
        r"give the change in MSE's deficit, paired by seed, against epoch "
        + str(first) + r" of the same run and against the end of the 200-epoch "
        r"schedule (first row). Brackets are 95\% $t$-intervals.}",
        r"\label{tab:deficit-budget}",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r" & MSE & \multicolumn{2}{c}{Deficit (dB)} & AWWL & "
        r"\multicolumn{2}{c}{MSE change in deficit} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){6-7}",
        r"Checkpoint & FID & MSE & AWWL & correction & vs.\ epoch " + str(first)
        + r" & vs.\ 200 ep. \\",
        r"\midrule",
        *rows_out,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    return "\n".join(lines)


