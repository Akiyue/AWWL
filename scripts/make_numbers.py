class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.names: dict[str, str] = {}

    def section(self, title: str) -> None:
        self.lines += ["", "% " + "-" * 74, f"% {title}", "% " + "-" * 74]

    def add(self, name: str, value: str | None, source: str) -> None:
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name must be letters only: {name!r}")
        if name in self.names:
            raise ValueError(f"macro defined twice: {name}")
        text = PLACEHOLDER if value is None or PLACEHOLDER in str(value) else str(value)
        self.names[name] = text
        self.lines.append(f"% {source}")
        self.lines.append("\\newcommand{\\" + name + "}{" + text + "}")

    def text(self) -> str:
        head = [
            "% Generated by scripts/make_numbers.py --- do not edit by hand.",
            "% Every macro is computed from the ledger or cache named in the comment",
            "% above it. SD: sample standard deviation (ddof = 1). Lo/Hi: 95% t-interval",
            "% of the mean paired difference. P: two-sided paired t-test, uncorrected.",
            "% Holm: Holm-Bonferroni within the fixed family named in the comment.",
            "% Negative values carry a minus sign (use them in math mode); positive",
            "% values carry no sign. \\textbf{??} marks a value whose rows do not exist yet.",
        ]
        return "\n".join(head + self.lines) + "\n"


def num(x: float | None, digits: int = 3) -> str | None:
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return None
    return mt.fnum(x, digits)


def bound(x: float | None, digits: int = 2) -> str | None:
    """An interval bound: one that would round to zero gains digits until it
    does not (``make_tables.fbound``), so a macro reads as the table does and
    ``[-0.73, 0.00]`` cannot stand for an interval that excludes zero."""
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return None
    return mt.fbound(x, digits)


def pval(p: float | None) -> str | None:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return None
    s = mt.fp(p)
    return "\\ensuremath{" + s + "}" if s.startswith("<") else s


def mean_sd(M: Macros, name: str, values: Mapping | Sequence | None, source: str,
            digits: int = 3, sd_digits: int | None = None) -> None:
    vals = list(values.values()) if isinstance(values, Mapping) else list(values or [])
    ok = len(vals) >= 2
    M.add(name + "mean", num(statistics.mean(vals), digits) if ok else None, source + "; mean over seeds")
    M.add(name + "sd", num(mt.sample_sd(vals), sd_digits or digits) if ok else None,
          source + "; sample SD over seeds (ddof=1)")
    M.add(name + "n", str(len(vals)) if vals else None, source + "; number of seeds")


def comparison(M: Macros, name: str, res: mt.Paired | None, source: str, *,
               digits: int = 3, ci_digits: int = 2, holm: str | None = None,
               sd: bool = False, n: bool = False) -> None:
    """``name`` (mean difference), ``nameLo``/``nameHi``, ``nameP`` and optionally more."""
    M.add(name, num(res.mean, digits) if res else None, source + "; mean paired difference")
    M.add(name + "Lo", bound(res.lo, ci_digits) if res else None, source + "; 95% t-interval, lower")
    M.add(name + "Hi", bound(res.hi, ci_digits) if res else None, source + "; 95% t-interval, upper")
    M.add(name + "P", pval(res.p) if res else None, source + "; two-sided paired t-test, raw")
    if holm is not None:
        M.add(name + "Holm", pval(res.p_holm) if res else None, source + f"; Holm over {holm}")
    if sd:
        M.add(name + "SD", num(res.sd, digits) if res else None, source + "; SD of the paired differences")
    if n:
        M.add(name + "N", str(res.n) if res else None, source + "; number of seed pairs")


def pearson(a: Mapping, b: Mapping) -> float | None:
    shared = sorted(set(a) & set(b), key=str)
    if len(shared) < 3:
        return None
    x, y = [a[s] for s in shared], [b[s] for s in shared]
    return statistics.correlation(x, y)


def _power(n: int, effect: float, alpha: float = 0.05) -> float:
    """Power of the two-sided one-sample t-test at standardised effect ``effect``.

    Integrates the normal tail probabilities over the chi-square distribution
    of the variance estimate, which stays accurate where scipy's noncentral t
    returns NaN (large noncentrality at small df).
    """
    from scipy import integrate, stats

    df = n - 1
    crit = stats.t.ppf(1 - alpha / 2, df)
    nc = effect * math.sqrt(n)

    def integrand(v: float) -> float:
        s = crit * math.sqrt(v / df)
        return (stats.norm.cdf(-s - nc) + stats.norm.sf(s - nc)) * stats.chi2.pdf(v, df)

    value, _ = integrate.quad(integrand, 0.0, math.inf, limit=200)
    return float(value)


def min_detectable(n: int, sd: float, *, power: float = 0.8, alpha: float = 0.05) -> float | None:
    """Smallest true paired difference a two-sided paired t-test detects with ``power``."""
    from scipy import optimize

    if n < 2 or sd <= 0:
        return None
    return float(optimize.brentq(lambda e: _power(n, e, alpha) - power, 1e-6, 20.0)) * sd


def power_at(n: int, sd: float, delta: float, alpha: float = 0.05) -> float | None:
    if n < 2 or sd <= 0:
        return None
    return _power(n, delta / sd, alpha)


