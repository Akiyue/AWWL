def words(n: int) -> str:
    """An integer below 1000 as camel-case words (``159`` -> ``OneFiftyNine``)."""
    if n < 20:
        return _ONES[n] or "Zero"
    if n < 100:
        return _TENS[n // 10] + _ONES[n % 10]
    rest = n % 100
    return _ONES[n // 100] + ("Hundred" if rest == 0 else words(rest))


