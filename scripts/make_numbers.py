def build(compute: bool = True, workers: int = 4) -> Macros:
    M = Macros()
    study_size(M)
    rows = main_matrix(M)
    replication(M, rows)
    pairing(M, rows)
    confound(M, rows)
    weighting(M)
    learned_weighting(M)
    extensions(M, rows)
    convergence(M)
    spectral(M, compute, workers)
    sampler(M, rows)
    budget(M, rows)
    dreambooth(M)
    celeba(M)
    restoration(M)
    pricing(M, rows)
    round_two(M, rows)
    dinov2(M)
    planted(M, rows)
    return M


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--no-compute", action="store_true", help="use cached spectral profiles only")
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()
    M = build(compute=not args.no_compute, workers=args.workers)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(M.text(), encoding="utf-8")
    pending = sum(1 for v in M.names.values() if v == PLACEHOLDER)
    print(f"wrote {args.out}: {len(M.names)} macros, {pending} placeholder(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
