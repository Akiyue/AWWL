def spectral(M: Macros, compute: bool, workers: int) -> None:
    M.section("Spectral statistic (all samples, all 50,000 reference images; runs/pricing/cache)")
    ref = mb.reference_profile(compute=compute)
    if ref is None:
        return
    (l0, l1), (m0, m1), (h0, h1) = mb.band_edges(len(ref))
    for name, value in (("bandLowMax", l1), ("bandMidMin", m0), ("bandMidMax", m1),
                        ("bandHighMin", h0), ("bandHighMax", h1)):
        M.add(name, str(value), "band_deviations: radii of the three equal index thirds of the profile")
    M.add("nRefImages", str(mb._count_images(mb.REAL)), "data/cifar10_train_png: reference images")
    arms = [a for a, _ in mb.ARMS]
    devs = mb.deviations(mb.ddim(), arms, mb.SEEDS, ref, compute=compute, workers=workers)
    src = "runs/pricing/cache/cifar10/profiles/*_ep199.npy vs ref_profile.npy"
    base = devs.get("mse", {})
    for band, bname in ((0, "Low"), (1, "Mid"), (2, "High")):
        vals = [-v[band] for v in base.values()]
        M.add("deficit" + bname + "MSE", num(statistics.mean(vals), 2) if len(vals) >= 2 else None,
              f"{src}: mse, minus the mean signed {bname.lower()}-band deviation (dB)")
        M.add("deficit" + bname + "MSEsd", num(mt.sample_sd(vals), 2) if len(vals) >= 2 else None,
              f"{src}: mse, sample SD of the {bname.lower()}-band deficit (dB)")
    for arm in arms:
        if arm == "mse":
            continue
        a = devs.get(arm, {})
        high = [-v[2] for v in a.values()]
        M.add("deficitHigh" + CODE[arm], num(statistics.mean(high), 2) if len(high) >= 2 else None,
              f"{src}: {arm}, high-band deficit (dB), mean over seeds")
        res = mt.paired({s: v[2] for s, v in a.items()}, {s: v[2] for s, v in base.items()})
        comparison(M, "corrHigh" + CODE[arm], res,
                   f"{src}: high-band deviation, {arm} - mse (dB; positive = correction)", digits=2)
    a = devs.get("awwl", {})
    for band, bname in ((0, "Low"), (1, "Mid")):
        res = mt.paired({s: v[band] for s, v in a.items()}, {s: v[band] for s, v in base.items()})
        comparison(M, "corr" + bname + "AWWL", res, f"{src}: {bname.lower()}-band deviation, awwl - mse (dB)",
                   digits=2)
    for band, bname in ((0, "Low"), (1, "Mid"), (2, "High")):
        res = mt.paired({s: v[band] for s, v in a.items()}, {s: v[band] for s, v in base.items()})
        deficit = statistics.mean(-v[band] for v in base.values()) if base else None
        M.add("share" + bname + "AWWL", f"{100 * res.mean / deficit:.0f}" if res and deficit else None,
              f"{src}: awwl's mean {bname.lower()}-band correction as a percentage of mse's deficit")

    M.section("Spectral statistic under DDPM-1000 (runs/pricing/cache/cifar10/profiles/*_ddpm1000.npy)")
    d = mb.deviations(mb.ddpm(), list(mb.DDPM_ARMS), mb.SEEDS, ref, compute=compute, workers=workers)
    b = d.get("mse", {})
    vals = [-v[2] for v in b.values()]
    M.add("deficitHighMSEddpm", num(statistics.mean(vals), 2) if len(vals) >= 2 else None,
          "DDPM-1000 samples: mse, high-band deficit (dB), mean over seeds")
    for arm in ("static_wavelet", "awwl"):
        res = mt.paired({s: v[2] for s, v in d.get(arm, {}).items()}, {s: v[2] for s, v in b.items()})
        comparison(M, "corrHigh" + CODE[arm] + "ddpm", res,
                   f"DDPM-1000 samples: high-band deviation, {arm} - mse (dB)", digits=2)

    M.section("Spectral statistic against training budget (Table deficit-budget)")
    anchor, long = mb.trajectory_data(ref, compute=compute, workers=workers)

    def neg(x):
        return {s: -v for s, v in x.items()}

    am, aa = neg(anchor.get("mse", {})), neg(anchor.get("awwl", {}))
    M.add("trajDefMSEend", num(statistics.mean(am.values()), 2) if len(am) >= 2 else None,
          "runs/phase0 mse_ema, epoch 199 (200-epoch schedule, annealed): high-band deficit (dB)")
    comparison(M, "trajCorrEnd", mt.paired(am, aa),
               "200-epoch EMA end: high-band deficit mse_ema - awwl_ema (dB; AWWL's correction)", digits=2)
    first = mb.TRAJECTORY_EPOCHS[0]
    last = mb.TRAJECTORY_EPOCHS[-1]
    for epoch in mb.TRAJECTORY_EPOCHS:
        lm, la = neg(long.get(epoch, {}).get("mse", {})), neg(long.get(epoch, {}).get("awwl", {}))
        w = words(epoch)
        src = f"runs/converged, epoch {epoch} (800-epoch EMA schedule)"
        M.add("trajDefMSE" + w, num(statistics.mean(lm.values()), 2) if len(lm) >= 2 else None,
              src + ": mse high-band deficit (dB), mean over seeds")
        M.add("trajDefMSEsd" + w, num(mt.sample_sd(list(lm.values())), 3) if len(lm) >= 2 else None,
              src + ": mse high-band deficit, sample SD")
        comparison(M, "trajCorr" + w, mt.paired(lm, la), src + ": mse - awwl high-band deficit (dB)", digits=2)
        if epoch != first:
            comparison(M, "trajGrowth" + w, mt.paired(lm, neg(long[first]["mse"])),
                       src + f": mse deficit change against epoch {first} of the same run (dB)",
                       digits=2, sd=True)
    lm = neg(long.get(last, {}).get("mse", {}))
    comparison(M, "trajEndToEnd", mt.paired(lm, am),
               f"mse high-band deficit: 800-epoch end (epoch {last}) - 200-epoch EMA end (dB)", digits=2, sd=True)


