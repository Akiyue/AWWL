"""Emit every number the manuscript's prose quotes as a LaTeX macro.

Writes ``paper/generated/numbers.tex``: one ``\\newcommand`` per number, each
preceded by a comment naming the ledger (or cache) and the computation it
comes from. The prose then writes ``\\fidMSEmean`` instead of ``18.460``, so a
re-run of this script updates every mention and nothing in the text has to be
transcribed by hand.

Conventions (the same as ``make_tables.py``):

* ``SD`` is the across-seed sample standard deviation (``ddof = 1``).
* ``Lo``/``Hi`` bound the 95% Student-t interval of a mean (paired)
  difference; ``P`` is the two-sided paired t-test, uncorrected; ``Holm`` is
  the Holm--Bonferroni-corrected p within the fixed family named in the
  comment (the ``FAMILY_*`` constants of ``make_tables.py``).
* Pairing is by training-seed ID.
* Numbers carry no explicit plus sign; negative numbers carry a minus sign and
  belong in math mode. Macro names are letters only.
* A p-value below 1e-4 is emitted as ``\\ensuremath{<10^{-4}}``.
* A value whose ledger rows do not exist yet (the pricing measurements, the
  corrected gradient-scale arm) is emitted as a visible placeholder,
  ``\\textbf{??}``, never as a guess.

Usage::

    python scripts/make_numbers.py
    python scripts/make_numbers.py --no-compute   # spectral caches only
"""

