def budget(M: Macros, rows: list[dict]) -> None:
    M.section("Four times the training budget (runs/converged, EMA, stretched cosine; Table budget)")
    conv_all = mt.load_eval(LEDGERS["converged"])
    long = [r for r in conv_all if r.get("epoch") == 799]
    anc = mt.load_eval(LEDGERS["converged_ddpm1000"], 799)
    ddpm = mt.load_eval(LEDGERS["phase0_ddpm1000"], 199)
    points = mt.budget_points(rows, rows, long, ddpm, anc)
    tags = {("200 epochs, no EMA", "DDIM-100"): "ShortDdim", ("200 epochs, EMA", "DDIM-100"): "ShortEmaDdim",
            ("800 epochs, EMA", "DDIM-100"): "LongDdim", ("200 epochs, no EMA", "DDPM-1000"): "ShortDdpm",
            ("800 epochs, EMA", "DDPM-1000"): "LongDdpm"}
    for budget_, sampler_, mb_, ma_, res in points:
        tag = tags[(budget_, sampler_)]
        src = f"Table budget, {budget_}, {sampler_}"
        M.add("budFIDMSE" + tag, num(statistics.mean(mb_.values()), 2), src + ": MSE FID, mean over seeds")
        M.add("budFIDMSEsd" + tag, num(mt.sample_sd(list(mb_.values())), 2), src + ": MSE FID, sample SD")
        M.add("budFIDAWWL" + tag, num(statistics.mean(ma_.values()), 2), src + ": AWWL FID, mean over seeds")
        M.add("budFIDAWWLsd" + tag, num(mt.sample_sd(list(ma_.values())), 2), src + ": AWWL FID, sample SD")
        # Holm: the Budget family (the two 800-epoch points) for the long
        # rows; each 200-epoch row keeps its home family's p (budget_points).
        home = {"ShortDdim": "FAMILY_MAIN", "ShortEmaDdim": "the one-test EMA pair",
                "ShortDdpm": "FAMILY_DDPM"}
        comparison(M, "budD" + tag, res, src + ": AWWL - MSE",
                   holm=home.get(tag, "the two 800-epoch points of Table budget (FAMILY_BUDGET)"),
                   sd=True, n=True)
    # Power of the three-seed comparison.
    r = next((p[4] for p in points if tags[(p[0], p[1])] == "LongDdim"), None)
    M.add("budPowerLong", f"{100 * power_at(r.n, r.sd, 0.3):.0f}" if r else None,
          "noncentral t: power (%) of the 800-epoch DDIM-100 paired test (n = 3, observed paired SD) "
          "to detect a true FID gap of 0.3 at alpha 0.05")
    # Every checkpoint of the longer runs.
    epochs = sorted({r.get("epoch") for r in conv_all if r.get("epoch") is not None})
    per_seed: dict = {}
    for e in epochs:
        sub = [r for r in conv_all if r.get("epoch") == e]
        res = mt.paired(mt.by_seed(sub, "awwl", "fid"), mt.by_seed(sub, "mse", "fid"))
        comparison(M, "longGap" + words(e), res, f"runs/converged/results.jsonl, epoch {e}: awwl - mse FID")
        if res:
            for s, d in zip(res.seeds, res.deltas, strict=True):
                per_seed.setdefault(s, []).append(d)
    avg = mt.one_sample([statistics.mean(v) for v in per_seed.values()], list(per_seed))
    comparison(M, "longGapAvg", avg, "runs/converged/results.jsonl: per-seed mean of the awwl - mse FID gap "
               "over every evaluated checkpoint, then a one-sample t-test across seeds")
    means = {e: statistics.mean(mt.by_seed([r for r in conv_all if r.get("epoch") == e], "mse", "fid").values())
             for e in epochs}
    best = min(means, key=means.get) if means else None
    M.add("longBestFIDMSE", num(means[best], 2) if best is not None else None,
          "runs/converged/results.jsonl: lowest mean MSE FID over the evaluated checkpoints")
    M.add("longBestEpochMSE", str(best) if best is not None else None,
          "runs/converged/results.jsonl: the epoch of longBestFIDMSE")
    for metric, code, scale, digits in (("is_mean", "IS", 1.0, 3), ("kid_tf", "KID", 1e3, 2)):
        res = mt.paired(mt.by_seed(long, "awwl", metric, scale), mt.by_seed(long, "mse", metric, scale))
        comparison(M, "longD" + code, res, f"runs/converged/results.jsonl, epoch 799, {metric}"
                   + (" x 1e3" if scale != 1 else "") + ": awwl - mse", digits=digits, ci_digits=digits)


def dreambooth(M: Macros) -> None:
    M.section("DreamBooth (runs/dreambooth_seeds; Table dreambooth)")
    path = LEDGERS["dreambooth_seeds"]
    rows = mt.load_eval(path)
    if not rows:
        return
    groups = sorted(mt.groups_of(rows))
    M.add("dbNobjectives", str(len(groups)), f"{rel(path)}: distinct groups")
    n_img = sorted({int(r["n_images"]) for r in rows if mt._valid(r.get("n_images"))})
    M.add("dbNimages", str(n_img[0]) if len(n_img) == 1 else None, f"{rel(path)}: n_images per run")
    n_pr = sorted({int(r["n_prompts"]) for r in rows if mt._valid(r.get("n_prompts"))})
    M.add("dbNprompts", str(n_pr[0]) if len(n_pr) == 1 else None, f"{rel(path)}: n_prompts per run")
    fam = f"FAMILY_DREAMBOOTH ({len(mt.FAMILY_DREAMBOOTH)} arms), within the metric"
    for metric, code in (("clip_score", "Clip"), ("similarity", "Sim")):
        means = {g: statistics.mean(mt.by_seed(rows, g, metric).values()) for g in groups}
        ranks = {g: i + 1 for i, g in enumerate(sorted(means, key=lambda g: -means[g]))}
        res = mt.compare_family(rows, metric, mt.FAMILY_DREAMBOOTH)
        for arm in ("awwl", "snr_weighted", "min_snr", "static_wavelet", "awwl_learned"):
            M.add("dbRank" + code + CODE[arm], str(ranks.get(arm)) if arm in ranks else None,
                  f"{rel(path)}, {metric}: rank of {arm} among all groups by mean")
            M.add("db" + code + CODE[arm] + "mean", num(means.get(arm), 4) if arm in means else None,
                  f"{rel(path)}, {metric}: {arm}, mean over seeds")
            comparison(M, "dbD" + code + CODE[arm], res.get(arm), f"{rel(path)}, {metric}: {arm} - mse",
                       digits=4, ci_digits=4, holm=fam)
        M.add("db" + code + "MSEmean", num(means.get("mse"), 4), f"{rel(path)}, {metric}: mse, mean over seeds")
        M.add("dbSeedSD" + code, num(mt.sample_sd(list(mt.by_seed(rows, "mse", metric).values())), 4),
              f"{rel(path)}, {metric}: mse, sample SD over seeds")
    r = mt.compare_family(rows, "clip_score", mt.FAMILY_DREAMBOOTH).get("snr_weighted")
    M.add("dbWilcoxonClipRawSNR", f"{r.wilcoxon:.4f}" if r and r.wilcoxon is not None else None,
          f"{rel(path)}, clip_score: snr_weighted - mse, two-sided Wilcoxon signed-rank test")

    pricing = RUNS / "dreambooth_seeds" / "pricing.jsonl"
    rows_p: dict[str, dict] = {}
    if pricing.exists():
        for line in pricing.read_text(encoding="utf-8").splitlines():
            if line.strip():
                row = json.loads(line)
                rows_p[row["exp"]] = row  # the last pass for each run wins
    src = f"{rel(pricing)} (last row per run)"

    def get(arm: str, key: str) -> dict:
        out = {}
        for exp, row in rows_p.items():
            g, _, s = exp.rpartition("_s")
            if g == arm and s.isdigit() and mt._valid(row.get(key)):
                out[int(s)] = float(row[key])
        return out

    dm, da = get("mse", "deficit_db"), get("awwl", "deficit_db")
    M.add("dbDefMSE", num(statistics.mean(dm.values()), 2) if dm else None, src + ": mse deficit_db, mean")
    M.add("dbDefAWWL", num(statistics.mean(da.values()), 2) if da else None, src + ": awwl deficit_db, mean")
    comparison(M, "dbCorr", mt.paired(dm, da), src + ": deficit_db mse - awwl (dB)", digits=2, sd=True)
    resid = get("mse", "boosted_deficit_db")
    M.add("dbResid", num(statistics.mean(resid.values()), 2) if resid else None,
          src + ": mse boosted_deficit_db (deficit left after the post-process), mean")
    for key, code in (("clip_score", "Clip"), ("similarity", "Sim")):
        diffs = [float(r[key + "_boosted"]) - float(r[key]) for r in rows_p.values()
                 if mt._valid(r.get(key)) and mt._valid(r.get(key + "_boosted"))]
        M.add("dbPrice" + code, num(statistics.mean(diffs), 5) if diffs else None,
              src + f": {key}_boosted - {key}, mean over all runs")
        M.add("dbPrice" + code + "SD", num(mt.sample_sd(diffs), 5) if diffs else None,
              src + f": {key}_boosted - {key}, sample SD over all runs")
        M.add("dbPrice" + code + "N", str(len(diffs)), src + ": runs entering the price")


