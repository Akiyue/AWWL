def weighting(M: Macros) -> None:
    """Averages of the published weighting over the timesteps training samples.

    ``sum_b`` runs over the four sub-bands with their effective weights: in the
    released (averaged) form each detail band carries ``w_det / 3``, in the
    summed form of the conference equation each carries ``w_det``.
    """
    M.section("The published weighting over the training timesteps (Section family, Table confound)")
    cfg = mt.run_config(RUNS / "phase0", "awwl").get("loss", {})
    alpha, power = float(cfg.get("alpha", 0.2)), float(cfg.get("power", 1.0))
    src = (f"AdaptiveWaveletLoss(alpha={alpha:g}, power={power:g}).weights_at(sigma_t) "
           "(alpha, power from runs/phase0/awwl_s1/config.json), sigma_t = sqrt(1 - alphabar_t) "
           "of the linear DDPM schedule, T = 1000; mean over the T timesteps")
    vals: dict[str, float] = {}
    try:
        from awwl.losses import AdaptiveWaveletLoss
        from awwl.plotting.paper_figures import _training_sigmas

        sig = _training_sigmas("linear")
        w = AdaptiveWaveletLoss(alpha=alpha, power=power).weights_at(sig)
        ll, det = w["w_ll"].double(), w["w_det"].double()
        vals = {
            "wTotalMean": float((ll + det).mean()),
            "wTotalMeanSummed": float((ll + 3.0 * det).mean()),
            "wSqMean": float((ll ** 2 + det ** 2 / 3.0).mean()),
            "wSqMeanSummed": float((ll ** 2 + 3.0 * det ** 2).mean()),
            "pctSigmaHigh": 100.0 * float((sig > 0.9).double().mean()),
        }
    except Exception as exc:  # pragma: no cover - torch/diffusers absent
        print(f"weighting averages unavailable: {exc}")
    M.add("wTotalMean", num(vals.get("wTotalMean"), 4),
          src + ": sum_b w_b = w_LL + w_det (detail bands averaged, the released form)")
    M.add("wTotalMeanSummed", num(vals.get("wTotalMeanSummed"), 4),
          src + ": sum_b w_b = w_LL + 3 w_det (detail bands summed)")
    M.add("wSqMean", num(vals.get("wSqMean"), 4),
          src + ": sum_b w_b^2 = w_LL^2 + w_det^2/3 (averaged form; awwl_grad_matched_mean pins this)")
    M.add("wSqMeanSummed", num(vals.get("wSqMeanSummed"), 4),
          src + ": sum_b w_b^2 = w_LL^2 + 3 w_det^2 (summed form; awwl_grad_matched pins this)")
    M.add("pctSigmaHigh", f"{vals['pctSigmaHigh']:.0f}" if "pctSigmaHigh" in vals else None,
          "the same schedule: percentage of the T training timesteps with sigma_t > 0.9")

    # Pearson correlation, over the training timesteps, between the published
    # total weight S(sigma_t) = w_LL + w_det and the Min-SNR-gamma multiplier
    # kappa_t = min(SNR_t, 5) / SNR_t, at the CIFAR-10 and DreamBooth settings.
    for name, a, pw, schedule, what in (
        ("rSMinSNRCifar", 0.2, 1.0, "linear", "alpha=0.2, p=1, linear DDPM schedule (CIFAR-10)"),
        ("rSMinSNRDB", 0.8, 2.0, "scaled_linear", "alpha=0.8, p=2, SD 1.5 scaled-linear schedule (DreamBooth)"),
    ):
        value = None
        try:
            import torch

            from awwl.losses import AdaptiveWaveletLoss
            from awwl.losses.weighting import min_snr_weight
            from awwl.plotting.paper_figures import _training_sigmas

            sig = _training_sigmas(schedule)
            w = AdaptiveWaveletLoss(alpha=a, power=pw).weights_at(sig)
            total = (w["w_ll"] + w["w_det"]).double()
            kappa = min_snr_weight(sig, gamma=5.0).double().reshape(-1)
            value = float(torch.corrcoef(torch.stack([total.reshape(-1), kappa]))[0, 1])
        except Exception as exc:  # pragma: no cover
            print(f"{name} unavailable: {exc}")
        M.add(name, num(value, 2), f"Pearson r(S(sigma_t), kappa_t) over the T = 1000 training timesteps, {what}")


